import torch


@torch.no_grad()
def padding(tensor, left=True):
    zeropadding = torch.zeros_like(tensor[:, -1:])
    if left:
        tensor = torch.cat((zeropadding, tensor[:, :-1]), dim=1)
    else:
        tensor = torch.cat((tensor[:, 1:], zeropadding), dim=1)
    return tensor


@torch.no_grad()
def same_doc_next_mask(ctx_doc_ids):
    """[B, seq] {0,1}: 1 iff position j and j+1 are the same document (last col 0)."""
    same = torch.zeros_like(ctx_doc_ids)
    same[:, :-1] = (ctx_doc_ids[:, :-1] == ctx_doc_ids[:, 1:]).to(same.dtype)
    return same
